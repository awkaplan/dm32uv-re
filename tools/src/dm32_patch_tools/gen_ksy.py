#!/usr/bin/env python3
"""Compile specs/ksy/*.ksy (Kaitai Struct 0.11) into read-write Python parsers, and lint them.

    python3 gen_ksy.py            # lint, then regenerate specs/generated/python/<id>.py
    python3 gen_ksy.py --check    # exit 1 if any .ksy breaks the rules below or any generated
                                  # file is stale, missing or orphaned; writes nothing
    python3 gen_ksy.py --lint     # rules only (no compiler needed)

RULES (specs/README.md "Evidence rules", Kaitai part), checked on every .ksy:
  - meta.id equals the file name (the generated module is named after meta.id);
  - every seq entry and every instances entry, in the root type and in every nested type, has a
    non-empty `doc`;
  - every such entry has an effective `-dm32-confidence`: its own key, else the nearest enclosing
    type's, else meta's. Every `-dm32-confidence` anywhere must be one of CONFIRMED / DATASHEET /
    STRUCTURAL / INFERRED.
  A file without any `doc-ref` gets a warning (sources belong there), not an error.

OUTPUT: Python only, `--read-write`. Python is what this repo's tools and tests run, and Kaitai
0.11 supports serialization only for Python and Java. Java (for a Ghidra loader, say) is easy to
add later as a second target, but generated Java is large, adds a JDK to every consumer and
would be committed unused; generate it on demand with the same compiler instead.

Each generated file starts with a header naming this script, the compiler version and the
sha256 of the .ksy it came from, followed by the compiler's own output unchanged (0.11's Python
output carries no version banner or timestamp, so it is deterministic as is). The header hash
lets --check detect a stale file even where the compiler is unavailable (stdlib-only CI): it
then verifies hashes, lints, and says it could not recompile. With the compiler it recompiles
and compares byte for byte.

COMPILER: $KSC, else `kaitai-struct-compiler` on PATH, else tools/.ksc/ (tools/fetch_ksc.sh,
which is run when nothing is found unless --no-fetch). It needs Java. Only 0.11 is accepted.

The YAML reader here is a strict subset parser (block mappings and sequences, flow [..] / {..},
quoted and plain scalars, | and > block scalars, comments). It is stdlib-only so the lint runs
anywhere; anything outside the subset (anchors, tags, multiple documents, tabs) is an error,
never a silent misparse. The Kaitai compiler remains the authority on the files' meaning.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[3]
KSY_DIR = REPO / "specs" / "ksy"
OUT_DIR = REPO / "specs" / "generated" / "python"
FETCH_KSC = REPO / "tools" / "fetch_ksc.sh"
LOCAL_KSC = REPO / "tools" / ".ksc" / "kaitai-struct-compiler-0.11" / "bin" / "kaitai-struct-compiler"
KSC_VERSION = "0.11"
CONFIDENCE = ("CONFIRMED", "DATASHEET", "STRUCTURAL", "INFERRED")
CONF_KEY = "-dm32-confidence"
HEADER_TAG = "# Generated by tools/src/dm32_patch_tools/gen_ksy.py"
HEADER_RE = re.compile(r"^# Source: specs/ksy/(?P<name>[^ ]+) sha256 (?P<sha>[0-9a-f]{64})$", re.M)


# --------------------------------------------------------------------------------------------
# YAML subset reader
# --------------------------------------------------------------------------------------------

class YamlError(ValueError):
    pass


def _strip_comment(s: str) -> str:
    """Remove a trailing `# comment` (a # at the start or after whitespace, outside quotes)."""
    quote = None
    for i, ch in enumerate(s):
        if quote:
            if ch == quote:
                if quote == "'" and i + 1 < len(s) and s[i + 1] == "'":
                    continue
                quote = None
            elif ch == "\\" and quote == '"':
                continue
        elif ch in "'\"" and (i == 0 or s[i - 1] in " \t[{,:"):
            quote = ch
        elif ch == "#" and (i == 0 or s[i - 1] in " \t"):
            return s[:i].rstrip()
    return s.rstrip()


def _unquote(s: str, lineno: int):
    if s.startswith("'"):
        if not s.endswith("'") or len(s) < 2:
            raise YamlError(f"line {lineno}: unterminated single-quoted scalar")
        return s[1:-1].replace("''", "'")
    if s.startswith('"'):
        if not s.endswith('"') or len(s) < 2:
            raise YamlError(f"line {lineno}: unterminated double-quoted scalar")
        body = s[1:-1]
        try:
            return body.encode("latin-1", "backslashreplace").decode("unicode_escape")
        except UnicodeDecodeError as e:
            raise YamlError(f"line {lineno}: bad escape in double-quoted scalar: {e}") from None
    return s


def _scalar(s: str, lineno: int):
    s = s.strip()
    if s[:1] in ("&", "*", "!", "%", "@", "`"):
        raise YamlError(f"line {lineno}: unsupported YAML construct {s[:1]!r} (anchors, aliases, "
                        f"tags and reserved indicators are outside this reader's subset)")
    if s[:1] in ("'", '"'):
        return _unquote(s, lineno)
    return s


def _flow(text: str, lineno: int):
    """Parse a complete flow collection ([..] or {..}) from text."""
    pos = 0

    def ws():
        nonlocal pos
        while pos < len(text) and text[pos] in " \t\n":
            pos += 1

    def item(stop: str):
        nonlocal pos
        ws()
        if pos < len(text) and text[pos] in "[{":
            return coll()
        if pos < len(text) and text[pos] in "'\"":
            q = text[pos]
            j = pos + 1
            while j < len(text):
                if text[j] == q:
                    if q == "'" and j + 1 < len(text) and text[j + 1] == "'":
                        j += 2
                        continue
                    break
                if text[j] == "\\" and q == '"':
                    j += 1
                j += 1
            if j >= len(text):
                raise YamlError(f"line {lineno}: unterminated quoted scalar in flow collection")
            val = _unquote(text[pos:j + 1], lineno)
            pos = j + 1
            return val
        j = pos
        depth = 0
        while j < len(text):
            ch = text[j]
            if ch in "([":
                depth += 1
            elif ch in ")]" and depth:
                depth -= 1
            elif depth == 0 and (ch in stop or ch == "," or
                                 (ch == ":" and "}" in stop and (j + 1 == len(text) or text[j + 1] in " ,}"))):
                break
            j += 1
        val = _scalar(text[pos:j], lineno)
        pos = j
        return val

    def coll():
        nonlocal pos
        opener = text[pos]
        closer = "]" if opener == "[" else "}"
        pos += 1
        out = [] if opener == "[" else {}
        while True:
            ws()
            if pos >= len(text):
                raise YamlError(f"line {lineno}: unterminated flow collection")
            if text[pos] == closer:
                pos += 1
                return out
            if opener == "[":
                out.append(item("]"))
            else:
                k = item("}")
                ws()
                if pos < len(text) and text[pos] == ":":
                    pos += 1
                    v = item("}")
                else:
                    v = None
                if k in out:
                    raise YamlError(f"line {lineno}: duplicate key {k!r}")
                out[k] = v
            ws()
            if pos < len(text) and text[pos] == ",":
                pos += 1
            elif pos < len(text) and text[pos] != closer:
                raise YamlError(f"line {lineno}: expected ',' or {closer!r} in flow collection")

    ws()
    result = coll()
    ws()
    if pos != len(text):
        raise YamlError(f"line {lineno}: text after flow collection: {text[pos:]!r}")
    return result


def _balanced(s: str) -> bool:
    depth, quote = 0, None
    for i, ch in enumerate(s):
        if quote:
            if ch == quote:
                quote = None
            elif ch == "\\" and quote == '"':
                pass
        elif ch in "'\"":
            quote = ch
        elif ch in "[{":
            depth += 1
        elif ch in "]}":
            depth -= 1
    return depth <= 0 and quote is None


def _split_key(content: str):
    """Split 'key: value' / 'key:' at the first ': ' outside quotes and brackets; None if no key."""
    quote, depth = None, 0
    for i, ch in enumerate(content):
        if quote:
            if ch == quote:
                quote = None
            continue
        if ch in "'\"" and i == 0:
            quote = ch
        elif ch in "[{":
            depth += 1
        elif ch in "]}":
            depth -= 1
        elif ch == ":" and depth == 0 and (i + 1 == len(content) or content[i + 1] == " "):
            return content[:i].strip(), content[i + 1:].strip()
    return None


class _Lines:
    def __init__(self, text: str):
        for n, raw in enumerate(text.splitlines(), 1):
            if "\t" in raw[:len(raw) - len(raw.lstrip(" \t"))]:
                raise YamlError(f"line {n}: tab in indentation")
        self.raw = text.splitlines()
        self.i = 0

    def peek(self):
        """Next significant line as (indent, content, lineno), skipping blanks and comments."""
        while self.i < len(self.raw):
            raw = self.raw[self.i]
            content = _strip_comment(raw)
            if content.strip() == "":
                self.i += 1
                continue
            if content.strip() in ("---", "...") and self.i == 0:
                self.i += 1
                continue
            if content.strip() in ("---", "..."):
                raise YamlError(f"line {self.i + 1}: multiple YAML documents are not supported")
            return len(content) - len(content.lstrip(" ")), content.strip(), self.i + 1
        return None


def _parse_value(lines: _Lines, rest: str, indent: int, lineno: int):
    """The value after 'key:' (or '- ') whose owner sits at column `indent`."""
    if rest == "":
        nxt = lines.peek()
        if nxt is None:
            return None
        n_ind, n_content, _ = nxt
        if n_ind > indent or (n_ind == indent and (n_content == "-" or n_content.startswith("- "))):
            return _parse_block(lines, n_ind)
        return None
    if rest[0] in "|>":
        m = re.fullmatch(r"([|>])([+-]?)(\d?)([+-]?)", rest)
        if not m:
            raise YamlError(f"line {lineno}: bad block scalar header {rest!r}")
        style, chomp = m.group(1), (m.group(2) or m.group(4))
        body: list[str] = []
        block_indent = None
        while lines.i < len(lines.raw):
            raw = lines.raw[lines.i]
            if raw.strip() == "":
                body.append("")
                lines.i += 1
                continue
            ind = len(raw) - len(raw.lstrip(" "))
            if ind <= indent:
                break
            if block_indent is None:
                block_indent = int(m.group(3)) + indent if m.group(3) else ind
            if ind < block_indent:
                break
            body.append(raw[block_indent:])
            lines.i += 1
        while body and body[-1] == "" and chomp != "+":
            body.pop()
        if style == "|":
            text = "\n".join(body)
        else:
            text, prev_blank = "", True
            for ln in body:
                if ln == "":
                    text += "\n"
                    prev_blank = True
                elif ln.startswith(" ") or prev_blank:
                    text += ("" if prev_blank or not text else "\n") + ln
                    prev_blank = ln.startswith(" ")
                else:
                    text += " " + ln
        return text + ("\n" if chomp != "-" and text else "")
    if rest[0] in "[{":
        text = rest
        while not _balanced(text):
            if lines.i >= len(lines.raw):
                raise YamlError(f"line {lineno}: unterminated flow collection")
            text += "\n" + _strip_comment(lines.raw[lines.i])
            lines.i += 1
        return _flow(text, lineno)
    if rest[0] in "'\"":
        text = rest
        while not (len(text) >= 2 and text.endswith(rest[0]) and not text.endswith("\\" + rest[0])):
            if lines.i >= len(lines.raw):
                raise YamlError(f"line {lineno}: unterminated quoted scalar")
            text += " " + lines.raw[lines.i].strip()
            lines.i += 1
        return _scalar(text, lineno)
    # plain scalar, possibly continued on more-indented lines
    text = rest
    while True:
        nxt = lines.peek()
        if nxt is None or nxt[0] <= indent:
            break
        text += " " + nxt[1]
        lines.i += 1
    return _scalar(text, lineno)


def _parse_block(lines: _Lines, indent: int):
    first = lines.peek()
    if first is None:
        return None
    _, content, _ = first
    if content == "-" or content.startswith("- "):
        seq = []
        while True:
            nxt = lines.peek()
            if nxt is None or nxt[0] < indent:
                break
            ind, content, lineno = nxt
            if ind > indent:
                raise YamlError(f"line {lineno}: unexpected indentation")
            if not (content == "-" or content.startswith("- ")):
                break
            body = content[1:].lstrip(" ")
            col = ind + (len(content) - len(body))
            if body == "":
                lines.i += 1
                seq.append(_parse_value(lines, "", ind, lineno))
            elif body[0] not in "[{" and _split_key(body) is not None:
                # an inline mapping: re-read this line as if the dash were spaces
                lines.raw[lines.i] = " " * col + body
                seq.append(_parse_block(lines, col))
            else:
                lines.i += 1
                seq.append(_parse_value(lines, body, ind, lineno))
        return seq
    mapping: dict = {}
    while True:
        nxt = lines.peek()
        if nxt is None or nxt[0] < indent:
            break
        ind, content, lineno = nxt
        if ind > indent:
            raise YamlError(f"line {lineno}: unexpected indentation")
        if content == "-" or content.startswith("- "):
            break
        kv = _split_key(content)
        if kv is None:
            raise YamlError(f"line {lineno}: expected 'key: value', got {content!r}")
        key = _scalar(kv[0], lineno)
        if key in mapping:
            raise YamlError(f"line {lineno}: duplicate key {key!r}")
        lines.i += 1
        mapping[key] = _parse_value(lines, kv[1], indent, lineno)
    return mapping


def parse_yaml(text: str):
    lines = _Lines(text)
    first = lines.peek()
    if first is None:
        return None
    doc = _parse_block(lines, first[0])
    rest = lines.peek()
    if rest is not None:
        raise YamlError(f"line {rest[2]}: unexpected content {rest[1]!r}")
    return doc


def load_ksy(path: pathlib.Path) -> dict:
    doc = parse_yaml(path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict):
        raise YamlError("top level is not a mapping")
    return doc


# --------------------------------------------------------------------------------------------
# Lint
# --------------------------------------------------------------------------------------------

def _nonempty(v) -> bool:
    return isinstance(v, str) and v.strip() != ""


def lint_ksy(path: pathlib.Path, doc: dict | None = None) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) for one .ksy against the specs/README.md Kaitai rules."""
    errors: list[str] = []
    warnings: list[str] = []
    try:
        doc = doc if doc is not None else load_ksy(path)
    except (YamlError, OSError) as e:
        return [f"cannot read: {e}"], []
    meta = doc.get("meta")
    if not isinstance(meta, dict):
        return ["no meta mapping"], []
    if meta.get("id") != path.stem:
        errors.append(f"meta.id is {meta.get('id')!r}; it must equal the file name {path.stem!r}")

    def walk_conf(node, where):
        if isinstance(node, dict):
            for k, v in node.items():
                if k == CONF_KEY and v not in CONFIDENCE:
                    errors.append(f"{where}: {CONF_KEY} {v!r} is not one of {'/'.join(CONFIDENCE)}")
                walk_conf(v, f"{where}/{k}")
        elif isinstance(node, list):
            for i, v in enumerate(node):
                walk_conf(v, f"{where}/{i}")
    walk_conf(doc, "")

    def walk_type(spec: dict, where: str, inherited):
        conf = spec.get(CONF_KEY, inherited)
        seq = spec.get("seq") or []
        if not isinstance(seq, list):
            errors.append(f"{where}/seq is not a list")
            seq = []
        for i, entry in enumerate(seq):
            name = entry.get("id", f"#{i}") if isinstance(entry, dict) else f"#{i}"
            if not isinstance(entry, dict):
                errors.append(f"{where}/seq/{i} is not a mapping")
                continue
            if not _nonempty(entry.get("doc")):
                errors.append(f"{where}/seq/{name}: missing doc")
            if entry.get(CONF_KEY, conf) is None:
                errors.append(f"{where}/seq/{name}: no {CONF_KEY} (own, type's or meta's)")
        inst = spec.get("instances") or {}
        if not isinstance(inst, dict):
            errors.append(f"{where}/instances is not a mapping")
            inst = {}
        for name, entry in inst.items():
            if not isinstance(entry, dict):
                errors.append(f"{where}/instances/{name} is not a mapping")
                continue
            if not _nonempty(entry.get("doc")):
                errors.append(f"{where}/instances/{name}: missing doc")
            if entry.get(CONF_KEY, conf) is None:
                errors.append(f"{where}/instances/{name}: no {CONF_KEY} (own, type's or meta's)")
        types = spec.get("types") or {}
        if not isinstance(types, dict):
            errors.append(f"{where}/types is not a mapping")
            types = {}
        for tname, tspec in types.items():
            if isinstance(tspec, dict):
                walk_type(tspec, f"{where}/types/{tname}", conf)
            else:
                errors.append(f"{where}/types/{tname} is not a mapping")

    walk_type(doc, "", meta.get(CONF_KEY))
    if "doc-ref" not in repr(doc):
        warnings.append("no doc-ref anywhere: cite the sources (specs/README.md)")
    return errors, warnings


# --------------------------------------------------------------------------------------------
# Compiler
# --------------------------------------------------------------------------------------------

class KscUnavailable(RuntimeError):
    pass


def find_ksc(fetch: bool = True) -> str:
    cands = [os.environ.get("KSC"), shutil.which("kaitai-struct-compiler"), str(LOCAL_KSC)]
    for c in cands:
        if c and os.path.isfile(c) and os.access(c, os.X_OK):
            return c
    if fetch and FETCH_KSC.exists():
        p = subprocess.run(["bash", str(FETCH_KSC)], capture_output=True, text=True)
        if p.returncode == 0 and LOCAL_KSC.exists():
            return str(LOCAL_KSC)
        raise KscUnavailable(f"tools/fetch_ksc.sh failed: {p.stderr.strip()[-400:]}")
    raise KscUnavailable("kaitai-struct-compiler not found ($KSC, PATH, tools/.ksc/); "
                         "run tools/fetch_ksc.sh")


def ksc_version(ksc: str) -> str:
    try:
        p = subprocess.run([ksc, "--version"], capture_output=True, text=True, timeout=120)
    except OSError as e:
        raise KscUnavailable(f"cannot run {ksc}: {e}") from None
    if p.returncode != 0:
        raise KscUnavailable(f"{ksc} --version failed (is Java installed?): "
                             f"{(p.stderr or p.stdout).strip()[-300:]}")
    m = re.search(r"kaitai-struct-compiler\s+(\S+)", p.stdout + p.stderr)
    return m.group(1) if m else (p.stdout + p.stderr).strip()


def compile_one(ksc: str, ksy: pathlib.Path, outdir: pathlib.Path) -> pathlib.Path:
    p = subprocess.run([ksc, "--read-write", "-t", "python", "--outdir", str(outdir),
                        "--import-path", str(KSY_DIR), str(ksy)],
                       capture_output=True, text=True, timeout=300)
    produced = outdir / f"{ksy.stem}.py"
    if p.returncode != 0 or not produced.exists():
        msg = (p.stderr + p.stdout).strip()
        raise RuntimeError(f"kaitai-struct-compiler failed on {ksy.name}:\n{msg[-2000:]}")
    return produced


def header(ksy: pathlib.Path) -> str:
    sha = hashlib.sha256(ksy.read_bytes()).hexdigest()
    return (f"{HEADER_TAG} - do not edit.\n"
            f"# Source: specs/ksy/{ksy.name} sha256 {sha}\n"
            f"# Compiler: kaitai-struct-compiler {KSC_VERSION} --read-write -t python\n"
            f"# Runtime: kaitaistruct {KSC_VERSION} (tools/pyproject.toml, group `specs`)\n")


def render(ksc: str, ksy: pathlib.Path, tmp: pathlib.Path) -> str:
    body = compile_one(ksc, ksy, tmp).read_text(encoding="utf-8")
    return header(ksy) + body


# --------------------------------------------------------------------------------------------
# Driver
# --------------------------------------------------------------------------------------------

def _rel(p: pathlib.Path) -> str:
    try:
        return str(p.relative_to(REPO))
    except ValueError:
        return str(p)


def ksy_files() -> list[pathlib.Path]:
    return sorted(KSY_DIR.glob("*.ksy"))


def generated_files() -> list[pathlib.Path]:
    out = []
    for p in sorted(OUT_DIR.glob("*.py")):
        try:
            if p.read_text(encoding="utf-8").startswith(HEADER_TAG):
                out.append(p)
        except OSError:
            pass
    return out


def run(mode: str, fetch: bool) -> int:
    rc = 0
    files = ksy_files()
    lint_ok = {}
    for ksy in files:
        errs, warns = lint_ksy(ksy)
        for w in warns:
            print(f"WARN  {ksy.name}: {w}")
        for e in errs:
            print(f"FAIL  {ksy.name}: {e}")
        lint_ok[ksy] = not errs
        rc |= 1 if errs else 0
    if mode == "lint":
        print(f"lint: {sum(lint_ok.values())}/{len(files)} file(s) clean")
        return rc

    expected = {OUT_DIR / f"{k.stem}.py": k for k in files}
    orphans = [p for p in generated_files() if p not in expected]

    try:
        ksc = find_ksc(fetch)
        ver = ksc_version(ksc)
        if ver != KSC_VERSION:
            raise KscUnavailable(f"{ksc} is version {ver}; this repo pins {KSC_VERSION}")
    except KscUnavailable as e:
        if mode != "check":
            print(f"FAIL  {e}")
            return 1
        print(f"NOTE  {e}\nNOTE  compiler unavailable: checking source hashes only")
        for out, ksy in expected.items():
            if not out.exists():
                print(f"FAIL  {_rel(out)} missing (run gen_ksy.py)")
                rc = 1
                continue
            m = HEADER_RE.search(out.read_text(encoding="utf-8")[:1000])
            sha = hashlib.sha256(ksy.read_bytes()).hexdigest()
            if not m or m.group("name") != ksy.name or m.group("sha") != sha:
                print(f"FAIL  {_rel(out)} is stale (source hash differs)")
                rc = 1
        for p in orphans:
            print(f"FAIL  {_rel(p)} has no specs/ksy source (orphan)")
            rc = 1
        return rc

    with tempfile.TemporaryDirectory(prefix="gen_ksy-") as td:
        tmp = pathlib.Path(td)
        for out, ksy in expected.items():
            try:
                text = render(ksc, ksy, tmp)
            except (RuntimeError, subprocess.TimeoutExpired) as e:
                print(f"FAIL  {e}")
                rc = 1
                continue
            current = out.read_text(encoding="utf-8") if out.exists() else None
            if mode == "check":
                if current != text:
                    print(f"FAIL  {_rel(out)} is {'missing' if current is None else 'stale'}"
                          f" (run gen_ksy.py)")
                    rc = 1
                else:
                    print(f"ok    {_rel(out)}")
            elif current != text:
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(text, encoding="utf-8")
                print(f"wrote {_rel(out)}")
            else:
                print(f"same  {_rel(out)}")
    for p in orphans:
        if mode == "check":
            print(f"FAIL  {_rel(p)} has no specs/ksy source (orphan)")
            rc = 1
        else:
            p.unlink()
            print(f"removed orphan {_rel(p)}")
    return rc


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0],
                                 epilog="See the module docstring for the rules enforced.")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true",
                   help="exit 1 if any rule fails or generated/ is stale; write nothing")
    g.add_argument("--lint", action="store_true", help="only check the rules (no compiler)")
    ap.add_argument("--no-fetch", action="store_true",
                    help="do not run tools/fetch_ksc.sh when no compiler is found")
    args = ap.parse_args(argv)
    mode = "check" if args.check else "lint" if args.lint else "generate"
    return run(mode, fetch=not args.no_fetch)


if __name__ == "__main__":
    sys.exit(main())
