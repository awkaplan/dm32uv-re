#!/usr/bin/env python3
"""Generate the GNU ld fragments that turn DM-32UV patch building into ordinary embedded linking.

Outputs (both committed, both regenerated by this script, never hand-edited):

  tools/link/dm32_stock_symbols.ld
      `PROVIDE(name = 0xADDR);` for every stock function a patch may call by name, plus the RAM
      cells / code labels defined in tools/include/dm32_patch_api.h. A patch declares a normal C
      prototype (`void display_fill_rect(int, int, int, int, u16);`), calls it, and the linker
      resolves the `bsr` to the stock address. PROVIDE only defines symbols the patch actually
      references, so including all ~2.7k names costs nothing.

  tools/link/dm32_patch_memory.ld
      MEMORY regions covering ONLY verified-free space (flash window and SRAM scratch window from
      data/allocations.json, minus every allocation listed there), REGION_ALIASes PATCH_FLASH /
      PATCH_SRAM for the largest of each, and a NOLOAD reservation section over every other
      address (stock flash incl. the per-unit sector and occupied_regions.json, existing patch
      allocations, IRAM, low SRAM, flash beyond the 1 MB chip). Consequences, both verified with
      this repo's csky-abiv2-elf-ld 2.27:
        * a section placed with `> PATCH_FLASH` that grows too big fails with
          "region `PATCH_FLASH_n' overflowed by N bytes";
        * a section given an explicit address that lands on anything claimed fails with
          "section .x VMA [...] overlaps section .dm32_reserved.<name> VMA [...]".

Symbol policy for dm32_stock_symbols.ld (see meta/functions.json):
  * CONFIRMED and STRUCTURAL names only. RAW (`FUN_xxxxxxxx`) entries are skipped: a RAW name
    carries no claim about what the function does, so linking against it by name is meaningless.
  * Names that collide with the C standard library or the implementation namespace (memmove,
    strcat, strtod, __anything, _Upper...) are emitted as `stock_<name>` instead. GCC emits
    implicit calls to memcpy/memmove/memset; silently binding those to a stock routine whose
    semantics were only reverse-engineered (strtod here is a 10-byte thunk) would be a trap.
  * IRAM functions (address < 0x03000000) get their IRAM (run-time) address, 0x00010000-based,
    not the flash load-image address they are copied from at boot. A `bsr` from the flash patch
    window reaches them (CK803S bsr32 range is +-64 MB).
  * API-header names (dm32_patch_api.h) are added too. When the header names a function that
    meta/functions.json already has at the same address, it is not duplicated; when the header
    names an address under a different name (os_sem_pend_ms = OSMutexPend_wrapper2), both names
    are provided. A header name whose address DISAGREES with functions.json is a hard error.

Validation performed on every run (fails loudly rather than emitting a wrong script):
  * every byte of the flash window is 0xFF in the full stock image;
  * the flash window intersects neither the per-unit sector, any `forbidden` entry, nor any
    data/firmware/patching/occupied_regions.json entry;
  * allocations are inside their window, do not overlap each other, and flash allocations are
    whole 4 KiB sectors;
  * every generated name is a valid C identifier and unique.

Usage (pure python, stdlib only; run on the host or in the image):
    python3 tools/src/dm32_patch_tools/gen_link_artifacts.py            # (re)generate
    python3 tools/src/dm32_patch_tools/gen_link_artifacts.py --check    # exit 1 if stale
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]

FLASH_BASE = 0x03000000
FLASH_CHIP_END = 0x03100000          # 1 MB GD25Q80
FLASH_XIP_END = 0x04000000           # 16 MB XIP window per HR_C7000 memory map
IRAM_LO, IRAM_HI = 0x00010000, 0x00058000
SRAM_LO, SRAM_HI = 0x18000000, 0x18008000
SECTOR = 0x1000

SPACES = {
    # name: (lo, hi) -- whole address space, used to compute the reservation complement
    "flash": (FLASH_BASE, FLASH_XIP_END),
    "iram": (IRAM_LO, IRAM_HI),
    "sram": (SRAM_LO, SRAM_HI),
}

IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")

# C standard library + common libgcc/newlib names a compiler or a patch author may reference
# implicitly. A stock function with one of these names is provided as stock_<name> instead.
LIBC_NAMES = frozenset("""
    abort abs acos asin atan atan2 atexit atof atoi atol bsearch calloc ceil cos cosh div exit
    exp fabs floor fmod free frexp getenv isalnum isalpha iscntrl isdigit isgraph islower
    isprint ispunct isspace isupper isxdigit labs ldexp ldiv log log10 longjmp malloc memchr
    memcmp memcpy memmove memset modf pow printf putchar puts qsort rand realloc setjmp sin
    sinh snprintf sprintf sqrt srand sscanf strcat strchr strcmp strcoll strcpy strcspn strerror
    strlen strncat strncmp strncpy strpbrk strrchr strspn strstr strtod strtok strtol strtoul
    strxfrm tan tanh tolower toupper vsnprintf vsprintf main _start bzero bcopy strnlen strdup
""".split())


def die(msg: str) -> "NoReturn":  # type: ignore[name-defined]
    sys.exit(f"gen_link_artifacts: ERROR: {msg}")


def h(x: int) -> str:
    return f"0x{x:08x}"


def sha256(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git_last_commit(path: pathlib.Path) -> str:
    try:
        r = subprocess.run(["git", "log", "-1", "--format=%H", "--", str(path)], cwd=ROOT,
                           capture_output=True, text=True, check=True)
        dirty = subprocess.run(["git", "status", "--porcelain", "--", str(path)], cwd=ROOT,
                               capture_output=True, text=True, check=True).stdout.strip()
        return (r.stdout.strip() or "untracked") + (" (working copy modified)" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown (git unavailable)"


