def compute_layout(alloc_doc: dict, occupied_doc: dict, stock: bytes) -> dict:
    windows = {w["name"]: w for w in parse_ranges(alloc_doc["windows"])}
    for need in ("flash", "sram"):
        if need not in windows:
            die(f"allocations.json has no '{need}' window")
    forbidden = parse_ranges(alloc_doc.get("forbidden", []))
    occupied = [{"name": f"occupied_regions.json[{FLASH_BASE + int(o['start'], 16):#010x}"
                         f"-{FLASH_BASE + int(o['end'], 16):#010x})", "lo": FLASH_BASE + int(o["start"], 16),
                 "hi": FLASH_BASE + int(o["end"], 16), "what": o["what"]}
                for o in occupied_doc["occupied"]]
    allocs = parse_ranges(alloc_doc["allocations"])

    fw = windows["flash"]
    if fw["lo"] % SECTOR or fw["hi"] % SECTOR:
        die("flash window is not sector-aligned")
    if fw["hi"] > FLASH_CHIP_END or fw["lo"] < FLASH_BASE:
        die("flash window lies outside the 1 MB program flash")
    for f in forbidden + occupied:
        if overlaps(fw["lo"], fw["hi"], f["lo"], f["hi"]):
            die(f"flash window {h(fw['lo'])}-{h(fw['hi'])} intersects forbidden/occupied "
                f"{f['name']} {h(f['lo'])}-{h(f['hi'])}")
    seg = stock[fw["lo"] - FLASH_BASE: fw["hi"] - FLASH_BASE]
    if len(seg) != fw["hi"] - fw["lo"]:
        die("stock image is shorter than the flash window")
    if seg.count(0xFF) != len(seg):
        bad = next(i for i, b in enumerate(seg) if b != 0xFF)
        die(f"flash window is NOT erased in the stock image: first non-0xFF byte at "
            f"{h(fw['lo'] + bad)}")
    sw = windows["sram"]
    if sw["lo"] < SRAM_LO or sw["hi"] > SRAM_HI:
        die("sram window lies outside SRAM")

    names = set()
    for a in allocs:
        if not IDENT_RE.match(a["name"]) or a["name"] in names:
            die(f"allocation name {a['name']!r} is not a unique identifier")
        names.add(a["name"])
        w = windows.get(a["space"])
        if w is None:
            die(f"allocation {a['name']}: unknown space {a['space']!r}")
        if a["lo"] < w["lo"] or a["hi"] > w["hi"]:
            die(f"allocation {a['name']} {h(a['lo'])}-{h(a['hi'])} is outside the "
                f"{a['space']} window")
        if a["space"] == "flash" and (a["lo"] % SECTOR or a["hi"] % SECTOR):
            die(f"flash allocation {a['name']} is not whole 4 KiB sectors")
    for i, a in enumerate(allocs):
        for b in allocs[i + 1:]:
            if overlaps(a["lo"], a["hi"], b["lo"], b["hi"]):
                die(f"allocations {a['name']} and {b['name']} overlap")

    # free = window - allocations, aligned to the window's own granularity
    free = {}
    for space, w in windows.items():
        align = int(w.get("align", "0x4"), 16)
        cuts = sorted((a["lo"], a["hi"]) for a in allocs if a["space"] == space)
        cur, gaps = w["lo"], []
        for lo, hi in cuts + [(w["hi"], w["hi"])]:
            if lo > cur:
                g_lo = (cur + align - 1) // align * align
                g_hi = lo // align * align
                if g_hi - g_lo >= 16:
                    gaps.append((g_lo, g_hi))
            cur = max(cur, hi)
        free[space] = gaps

    # reservations = complement of free within each whole address space, split so each
    # allocation gets its own named section and the rest is labelled by what is there.
    reserved = []
    for space, (s_lo, s_hi) in SPACES.items():
        holes = sorted(free.get(space, []))
        cur, comp = s_lo, []
        for lo, hi in holes + [(s_hi, s_hi)]:
            if lo > cur:
                comp.append((cur, lo))
            cur = max(cur, hi)
        for c_lo, c_hi in comp:
            pts = {c_lo, c_hi}
            for a in allocs:
                if overlaps(c_lo, c_hi, a["lo"], a["hi"]):
                    pts.update((max(c_lo, a["lo"]), min(c_hi, a["hi"])))
            pts = sorted(pts)
            for lo, hi in zip(pts, pts[1:]):
                owner = next((a for a in allocs if a["lo"] <= lo and hi <= a["hi"]), None)
                reserved.append(_describe(space, lo, hi, owner, forbidden, occupied, windows))
    reserved.sort(key=lambda r: r["lo"])
    for i, r in enumerate(reserved):
        for s in reserved[i + 1:]:
            if overlaps(r["lo"], r["hi"], s["lo"], s["hi"]):
                die(f"internal: reservations {r['name']} and {s['name']} overlap")
    return {"windows": windows, "allocs": allocs, "free": free, "reserved": reserved,
            "forbidden": forbidden, "occupied": occupied}


def _describe(space, lo, hi, owner, forbidden, occupied, windows) -> dict:
    if owner is not None:
        return {"name": owner["name"], "lo": lo, "hi": hi,
                "why": f"allocated: {owner['owner']} [{owner['source']}]"}
    if space == "flash" and lo >= FLASH_CHIP_END:
        return {"name": "flash_not_present", "lo": lo, "hi": hi,
                "why": "XIP window beyond the 1 MB GD25Q80: no flash behind these addresses"}
    if space == "flash" and hi <= windows["flash"]["lo"]:
        inside = [f["name"] for f in forbidden + occupied if overlaps(lo, hi, f["lo"], f["hi"])]
        return {"name": "stock_flash", "lo": lo, "hi": hi,
                "why": "stock firmware (vendor update file 0x03000000-0x030d20ff) and, inside it: "
                       + ", ".join(inside)}
    if space == "iram":
        return {"name": "stock_iram", "lo": lo, "hi": hi,
                "why": "IRAM: uC/OS-III, drivers, stacks, runtime state; no verified-free space "
                       "(docs/rtos-and-memory.md)"}
    if space == "sram" and hi <= windows["sram"]["lo"]:
        return {"name": "stock_sram", "lo": lo, "hi": hi,
                "why": "SRAM: modem-owned 0x18000000-0x180007ff + initialised-data image "
                       "0x18000800-0x18004bfc (occupied_regions.json)"}
    return {"name": f"{space}_alignment_{lo:08x}", "lo": lo, "hi": hi,
            "why": f"{space} window remainder too small or misaligned to hand out"}


