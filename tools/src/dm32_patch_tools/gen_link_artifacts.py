def symbol_entries(funcs: list[dict], api: list[dict]) -> list[dict]:
    """Merged, validated list of every symbol to PROVIDE."""
    by_addr = {f["addr"]: f for f in funcs}
    by_name = {f["name"]: f for f in funcs}
    syms, seen = [], {}

    def add(name, addr, comment, source):
        if not IDENT_RE.match(name):
            die(f"{name!r} is not a valid identifier")
        if name in seen:
            if seen[name] != addr:
                die(f"symbol {name} defined at both {h(seen[name])} and {h(addr)}")
            return
        seen[name] = addr
        syms.append({"name": name, "addr": addr, "comment": comment, "source": source})

    for f in sorted(funcs, key=lambda f: f["addr"]):
        if f["confidence"] not in ("CONFIRMED", "STRUCTURAL"):
            continue
        note = f"{f['confidence']} size={f['size']} {f['subsystem']}"
        if f["link_name"] != f["name"]:
            note += f" (corpus name {f['name']}, renamed: C-library namespace)"
        if f["addr"] < FLASH_BASE:
            note += " IRAM"
        add(f["link_name"], f["addr"], note, "functions")
    for a in api:
        corpus = by_name.get(a["name"])
        if corpus is not None and corpus["addr"] != a["addr"]:
            die(f"dm32_patch_api.h {a['name']} = {h(a['addr'])} but meta/functions.json has "
                f"{h(corpus['addr'])}")
        if a["kind"] == "func" and corpus is None and a["addr"] not in by_addr:
            print(f"gen_link_artifacts: warning: API function {a['name']} @{h(a['addr'])} is not "
                  f"a function entry in meta/functions.json", file=sys.stderr)
        alias = by_addr.get(a["addr"]) if a["kind"] == "func" else None
        note = f"dm32_patch_api.h {a['kind']}: {a['type']}"
        if alias is not None and alias["name"] != a["name"]:
            note += f" (alias of {alias['name']})"
        add(a["name"], a["addr"], note, "api")
    return syms


def header(title: str, inputs: list[tuple[str, pathlib.Path]], extra: list[str]) -> str:
    lines = [f"/* {title}", " *",
             " * GENERATED by tools/src/dm32_patch_tools/gen_link_artifacts.py -- DO NOT EDIT.",
             " * Regenerate: python3 tools/src/dm32_patch_tools/gen_link_artifacts.py",
             " * Staleness check: the same command with --check.", " *", " * Inputs:"]
    for label, p in inputs:
        rel = p.relative_to(ROOT)
        lines.append(f" *   {rel}")
        lines.append(f" *     sha256 {sha256(p)}")
        lines.append(f" *     git-commit {git_last_commit(p)}")
    lines.append(" *")
    lines += [f" * {x}" if x else " *" for x in extra]
    lines.append(" */")
    return "\n".join(lines) + "\n"


def emit_symbols(funcs, api, inputs) -> str:
    syms = symbol_entries(funcs, api)
    n_conf = sum(1 for f in funcs if f["confidence"] == "CONFIRMED")
    n_struct = sum(1 for f in funcs if f["confidence"] == "STRUCTURAL")
    n_raw = sum(1 for f in funcs if f["confidence"] == "RAW")
    renamed = sorted(f"{f['name']}->{f['link_name']}" for f in funcs
                     if f["confidence"] != "RAW" and f["link_name"] != f["name"])
    out = [header("dm32_stock_symbols.ld -- stock DM32.00.01.048 symbols for patch linking", inputs, [
        "Confidence policy: CONFIRMED (" + str(n_conf) + ") and STRUCTURAL (" + str(n_struct) + ")",
        "functions from meta/functions.json are provided; RAW (" + str(n_raw) + ", FUN_xxxxxxxx) are not.",
        "STRUCTURAL means the name describes the code's shape, not a behaviour confirmed on",
        "hardware -- read the decompiled source (src/) before relying on one.",
        "Names in the C-library namespace are provided as stock_<name>: " + ", ".join(renamed) + ".",
        "Functions marked IRAM are given their run-time IRAM address (copied there from flash",
        "0x030bfc20.. at boot); call them at that address, never at the flash load image.",
        "The final block adds every address-valued #define in tools/include/dm32_patch_api.h",
        "(functions, RAM cells, code labels). For a RAM cell the symbol's VALUE is the cell's",
        "address: `extern volatile unsigned int KEYPAD_POLL_ENABLE;` then `KEYPAD_POLL_ENABLE = 0;`",
        "(do not also #include dm32_patch_api.h in that file -- its macros of the same names would",
        "expand first).",
        "",
        "PROVIDE() defines a symbol only if the link references it and nothing else defines it,",
        "so this whole file can be INCLUDEd into every patch link at no cost.",
    ])]
    out.append("\n/* ---- meta/functions.json (CONFIRMED + STRUCTURAL), by address ---- */\n")
    for s in syms:
        if s["source"] == "api":
            continue
        out.append(f"PROVIDE({s['name']} = {h(s['addr'])});  /* {cmt(s['comment'])} */\n")
    out.append("\n/* ---- tools/include/dm32_patch_api.h ---- */\n")
    for s in syms:
        if s["source"] == "api":
            out.append(f"PROVIDE({s['name']} = {h(s['addr'])});  /* {cmt(s['comment'])} */\n")
    return "".join(out)


def emit_memory(layout, inputs) -> str:
    free, reserved, allocs = layout["free"], layout["reserved"], layout["allocs"]
    regions = []
    for space, attrs in (("flash", "rx"), ("sram", "rw!x")):
        for i, (lo, hi) in enumerate(free[space]):
            regions.append((f"PATCH_{space.upper()}_{i}", attrs, lo, hi, space))
    out = [header("dm32_patch_memory.ld -- verified-free memory for DM-32UV patches", inputs, [
        "Free space = the flash/SRAM windows in data/allocations.json minus every allocation",
        "listed there (flash rounded to whole 4 KiB sectors). The flash window was re-checked to",
        "be all-0xFF in the full stock image and disjoint from the per-unit sector 0x0300b000",
        "and from every data/firmware/patching/occupied_regions.json entry when this was generated.",
        "",
        "USE: INCLUDE this file at the top level of your linker script and place sections with",
        "`> PATCH_FLASH` / `> PATCH_SRAM` (or a specific PATCH_<SPACE>_<n>). Overflowing a region",
        "fails the link. Every address that is NOT free is covered by a NOLOAD section named",
        ".dm32_reserved.<what>; a section given an explicit address that overlaps one fails the",
        "link with 'section ... overlaps section .dm32_reserved.<what>'.",
        "The reservations are NOBITS: they add nothing to `objcopy -O binary` output, but they do",
        "appear as zero-file-size PT_LOAD segments in the patch ELF. Extract the patch with",
        "objcopy (as every build script here does); never load the patch ELF itself onto a target.",
        "",
        "To claim space for a new patch: add it to data/allocations.json and regenerate.",
    ])]
    out.append("\nMEMORY\n{\n")
    for name, attrs, lo, hi, space in regions:
        out.append(f"    {name:<16} ({attrs}) : ORIGIN = {h(lo)}, LENGTH = 0x{hi - lo:x}"
                   f"    /* {h(lo)}-{h(hi - 1)}, {(hi - lo) // 1024} KiB")
        if space == "flash":
            out.append(f", sectors {(lo - FLASH_BASE) // SECTOR}-{(hi - FLASH_BASE) // SECTOR - 1}")
        out.append(" */\n")
    out.append("}\n\n")
    for space in ("flash", "sram"):
        rs = [r for r in regions if r[4] == space]
        if not rs:
            die(f"no free {space} left")
        big = max(rs, key=lambda r: r[3] - r[2])
        out.append(f"REGION_ALIAS(\"PATCH_{space.upper()}\", {big[0]});   /* largest free {space} region */\n")
    out.append("\n/* Existing claims, as symbols (for build scripts / sanity checks). */\n")
    for a in allocs:
        out.append(f"PROVIDE(__dm32_alloc_{a['name']}_start = {h(a['lo'])});\n")
        out.append(f"PROVIDE(__dm32_alloc_{a['name']}_end = {h(a['hi'])});\n")
    out.append("\n/* Everything that is not free. NOLOAD: never emitted, only collision-checked. */\n")
    out.append("SECTIONS\n{\n")
    for r in reserved:
        out.append(f"    /* {cmt(r['why'])} */\n")
        out.append(f"    .dm32_reserved.{r['name']} {h(r['lo'])} (NOLOAD) : "
                   f"{{ . = . + 0x{r['hi'] - r['lo']:x}; }}\n")
    out.append("}\n")
    return "".join(out)


def cmt(text: str) -> str:
    """Make arbitrary text safe inside a /* */ comment."""
    return text.replace("*/", "* /")


def strip_volatile(text: str) -> str:
    """Drop the git-commit lines so --check compares content-derived output only."""
    return "\n".join(l for l in text.splitlines() if "git-commit" not in l)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--functions", type=pathlib.Path, default=ROOT / "meta/functions.json")
    ap.add_argument("--api-header", type=pathlib.Path,
                    default=ROOT / "tools/include/dm32_patch_api.h")
    ap.add_argument("--allocations", type=pathlib.Path, default=ROOT / "data/allocations.json")
    ap.add_argument("--occupied", type=pathlib.Path,
                    default=ROOT / "data/firmware/patching/occupied_regions.json")
    ap.add_argument("--stock-image", type=pathlib.Path,
                    default=ROOT / "data/firmware/patching/progmem_stock_DP570UV_20260926_FULL.bin")
    ap.add_argument("--out-dir", type=pathlib.Path, default=ROOT / "tools/link")
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if the committed outputs are stale")
    args = ap.parse_args(argv)
    for p in ("functions", "api_header", "allocations", "occupied", "stock_image"):
        setattr(args, p, getattr(args, p).resolve())

    funcs = load_functions(args.functions)
    api = load_api_header(args.api_header)
    layout = compute_layout(json.loads(args.allocations.read_text()),
                            json.loads(args.occupied.read_text()), args.stock_image.read_bytes())

    outputs = {
        "dm32_stock_symbols.ld": emit_symbols(
            funcs, api, [("functions", args.functions), ("api", args.api_header)]),
        "dm32_patch_memory.ld": emit_memory(
            layout, [("allocations", args.allocations), ("occupied", args.occupied),
                     ("stock", args.stock_image)]),
    }
    if args.check:
        stale = [n for n, txt in outputs.items()
                 if not (args.out_dir / n).exists()
                 or strip_volatile((args.out_dir / n).read_text()) != strip_volatile(txt)]
        for n in stale:
            print(f"STALE: {args.out_dir / n}", file=sys.stderr)
        return 1 if stale else 0
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for n, txt in outputs.items():
        (args.out_dir / n).write_text(txt)
        print(f"wrote {args.out_dir / n} ({txt.count('PROVIDE(')} PROVIDE, "
              f"{txt.count('(NOLOAD)')} reservations)")
    for space in ("flash", "sram"):
        for lo, hi in layout["free"][space]:
            print(f"  free {space}: {h(lo)}-{h(hi - 1)} ({(hi - lo) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
