def link_name(name: str) -> str:
    """The name a stock function is exposed under at link level (see module docstring)."""
    if name in LIBC_NAMES or name.startswith("__") or re.match(r"_[A-Z]", name):
        return "stock_" + name.lstrip("_")
    return name


def load_functions(path: pathlib.Path) -> list[dict]:
    funcs = json.loads(path.read_text())["functions"]
    out = []
    for e in funcs:
        name = e["name"]
        if not IDENT_RE.match(name):
            die(f"{path}: {name!r} is not a valid identifier")
        out.append({
            "name": name,
            "link_name": link_name(name),
            "addr": int(e["addr"], 16),
            "size": int(e.get("size") or 0),
            "confidence": e["confidence"],
            "subsystem": e.get("subsystem", ""),
        })
    return out


_DEFINE_RE = re.compile(r"^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.*)$")
_PTR_CAST_RE = re.compile(r"^\(\((?P<type>.+)\)\s*(?P<addr>0[xX][0-9a-fA-F]+)\s*\)$")
_BARE_HEX_RE = re.compile(r"^(?P<addr>0[xX][0-9a-fA-F]+)$")
_SCALAR_SIZES = {"u8": 1, "u16": 2, "u32": 4, "char": 1, "short": 2, "int": 4}


def _in_known_space(addr: int) -> bool:
    # end-inclusive: an exclusive upper bound such as PATCH_SRAM_SCRATCH_HI (0x18008000) counts
    return (FLASH_BASE <= addr <= FLASH_CHIP_END or IRAM_LO <= addr <= IRAM_HI
            or SRAM_LO <= addr <= SRAM_HI)


def load_api_header(path: pathlib.Path) -> list[dict]:
    """Parse `#define NAME ((type)0xADDR)` and `#define NAME 0xADDR` (address-valued only).

    kind: 'func'  -- cast to a pointer-to-function `(ret (*)(args))`
          'object'-- cast to a data pointer (RAM cell / table / OS object)
          'label' -- bare hex constant inside a known memory space (code/data address)
    Function-like macros (UI_LANG_IS_ENGLISH()) and small constants (SCAN_*) are skipped.
    """
    text = re.sub(r"/\*.*?\*/", " ", path.read_text(), flags=re.S)   # strip comments first
    text = re.sub(r"\\\n", " ", text)                                 # join continuations
    out = []
    for line in text.splitlines():
        m = _DEFINE_RE.match(line)
        if not m:
            continue
        name, body = m.group(1), m.group(2).strip()
        body = re.sub(r"//.*$", "", body).strip()
        pm = _PTR_CAST_RE.match(body)
        if pm:
            typ = " ".join(pm.group("type").split())
            addr = int(pm.group("addr"), 16)
            if re.search(r"\(\s*\*\s*\)\s*\(", typ):
                kind, size = "func", 0
            else:
                kind = "object"
                base = re.sub(r"\b(volatile|const)\b", "", typ).replace("*", "").strip()
                size = _SCALAR_SIZES.get(base, 0) if typ.count("*") == 1 else 0
            out.append({"name": name, "addr": addr, "kind": kind, "type": typ, "size": size})
            continue
        bm = _BARE_HEX_RE.match(body)
        if bm and _in_known_space(int(bm.group("addr"), 16)):
            out.append({"name": name, "addr": int(bm.group("addr"), 16), "kind": "label",
                        "type": "address constant", "size": 0})
    return out


def parse_ranges(entries: list[dict]) -> list[dict]:
    out = []
    for e in entries:
        lo, hi = int(e["start"], 16), int(e["end_exclusive"], 16)
        if hi <= lo:
            die(f"empty/negative range in allocations.json entry {e.get('name')}")
        out.append({**e, "lo": lo, "hi": hi})
    return out


def overlaps(a_lo: int, a_hi: int, b_lo: int, b_hi: int) -> bool:
    return a_lo < b_hi and b_lo < a_hi


